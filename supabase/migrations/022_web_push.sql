-- Phone push notifications (user, 2026-11-13). Staff allow notifications in the app (PWA); each browser/phone
-- subscription is stored here. When a row is added to notifications, pg_net calls the Edge Function "send-push",
-- which sends it to that user's phones with Web Push (VAPID). The VAPID private key is kept in Vault and read only
-- by the service role (get_vapid_keys()); the public key is in index.html.
create extension if not exists pg_net with schema extensions;

create table public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  endpoint text not null unique check (char_length(endpoint) <= 1000),
  p256dh text not null check (char_length(p256dh) <= 200),
  auth text not null check (char_length(auth) <= 100),
  user_agent text check (char_length(user_agent) <= 300),
  created_at timestamptz not null default now()
);
create index push_subscriptions_user_idx on public.push_subscriptions (user_id);
alter table public.push_subscriptions enable row level security;
create policy "push subs own" on public.push_subscriptions for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

alter table public.notifications add column pushed_at timestamptz;

create or replace function public.get_vapid_keys() returns table (public_key text, private_key text)
language sql stable security definer set search_path = public, vault as $$
  select (select decrypted_secret from vault.decrypted_secrets where name = 'vapid_public_key'),
         (select decrypted_secret from vault.decrypted_secrets where name = 'vapid_private_key');
$$;
revoke all on function public.get_vapid_keys() from public, anon, authenticated;
grant execute on function public.get_vapid_keys() to service_role;

create or replace function public.trg_notification_push() returns trigger
language plpgsql security definer set search_path = public, extensions as $$
begin
  perform net.http_post(
    url := 'https://ijfmfeodnzkltxregfko.supabase.co/functions/v1/send-push',
    body := jsonb_build_object('id', new.id),
    headers := '{"Content-Type":"application/json"}'::jsonb);
  return null;
exception when others then
  return null; -- a push problem must never block the notification itself
end $$;
create trigger notification_push after insert on public.notifications
  for each row execute function public.trg_notification_push();
-- Vault secrets vapid_public_key / vapid_private_key are created separately (not stored in the repo).

-- 022b (same day): the VAPID key pair is generated by the Edge Function itself on first use and stored in Vault,
-- so the private key never leaves Supabase. The app reads only the public key.
create or replace function public.set_vapid_keys(p_public text, p_private text) returns void
language plpgsql security definer set search_path = public, vault as $$
begin
  if exists (select 1 from vault.secrets where name = 'vapid_private_key') then return; end if;
  perform vault.create_secret(p_public, 'vapid_public_key', 'Web Push public key');
  perform vault.create_secret(p_private, 'vapid_private_key', 'Web Push private key');
end $$;
revoke all on function public.set_vapid_keys(text, text) from public, anon, authenticated;
grant execute on function public.set_vapid_keys(text, text) to service_role;

create or replace function public.get_vapid_public() returns text
language sql stable security definer set search_path = public, vault as $$
  select decrypted_secret from vault.decrypted_secrets where name = 'vapid_public_key';
$$;
revoke all on function public.get_vapid_public() from public, anon;
grant execute on function public.get_vapid_public() to authenticated;
